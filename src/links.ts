export interface LinkOptions {
  /**
   * Target attribute for external links (e.g. '_blank', '_self').
   * External links are determined by starting with `http://`, `https://`, or `//`.
   * @default '_blank'
   */
  externalTarget?: '_blank' | '_self' | '_parent' | '_top' | string;

  /**
   * Rel attribute for external links.
   * @default 'noopener noreferrer'
   */
  externalRel?: string;

  /**
   * Custom attributes to inject into SVG `<a>` elements.
   * Can be an object of static attributes or a function receiving the `href` and returning attributes.
   * Useful for Astro prefetch (`data-astro-prefetch`), Next.js router attributes, or analytics.
   */
  attributes?:
    | Record<string, string>
    | ((href: string) => Record<string, string> | undefined);

  /**
   * Custom URL rewriter or transformer.
   * E.g. `(href) => href.startsWith('/') ? `/docs${href}` : href`
   */
  transformHref?: (href: string) => string;
}

const EXTERNAL_URL_REGEX = /^(?:https?:)?\/\//i;
const JAVASCRIPT_PROTOCOL_REGEX = /^\s*javascript:/i;

function escapeAttribute(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

/**
 * Enhances SVG anchor elements (`<a ...>`) generated by Pele / Mermaid.
 * Sanitizes URLs, adds configurable external targets/rel, and injects custom router attributes.
 */
export function enhanceSvgLinks(
  svg: string,
  options: LinkOptions = {},
): string {
  if (!svg.includes('<a ') && !svg.includes('<a>')) {
    return svg;
  }

  return svg.replace(/<a\b([^>]*)>/gi, (_match, rawAttrs) => {
    // Extract existing href
    const hrefMatch =
      rawAttrs.match(/\bhref="([^"]*)"/i) ||
      rawAttrs.match(/\bhref='([^']*)'/i);
    let href = hrefMatch ? hrefMatch[1] : '';

    // Disallow dangerous protocols
    if (JAVASCRIPT_PROTOCOL_REGEX.test(href)) {
      href = '#';
    }

    if (options.transformHref && href) {
      href = options.transformHref(href);
    }

    const isExternal = EXTERNAL_URL_REGEX.test(href);

    // Existing target and rel
    const targetMatch =
      rawAttrs.match(/\btarget="([^"]*)"/i) ||
      rawAttrs.match(/\btarget='([^']*)'/i);
    let target = targetMatch ? targetMatch[1] : undefined;

    const relMatch =
      rawAttrs.match(/\brel="([^"]*)"/i) || rawAttrs.match(/\brel='([^']*)'/i);
    let rel = relMatch ? relMatch[1] : undefined;

    const defaultExternalTarget =
      options.externalTarget !== undefined ? options.externalTarget : '_blank';
    const defaultExternalRel =
      options.externalRel !== undefined
        ? options.externalRel
        : 'noopener noreferrer';

    if (isExternal) {
      if (target === undefined && defaultExternalTarget) {
        target = defaultExternalTarget;
      }
      if (rel === undefined && defaultExternalRel) {
        rel = defaultExternalRel;
      }
    }

    // Extract remaining attributes
    const attrMap = new Map<string, string>();
    const attrRegex =
      /([a-zA-Z0-9_-]+)(?:=(?:"([^"]*)"|'([^']*)'|([^>\s]+)))?/g;
    let attrEntry: RegExpExecArray | null = attrRegex.exec(rawAttrs);

    while (attrEntry !== null) {
      const name = attrEntry[1];
      const val = attrEntry[2] ?? attrEntry[3] ?? attrEntry[4] ?? '';
      if (!['href', 'target', 'rel'].includes(name.toLowerCase())) {
        attrMap.set(name, val);
      }
      attrEntry = attrRegex.exec(rawAttrs);
    }

    // Inject custom attributes
    let customAttrs: Record<string, string> | undefined;
    if (typeof options.attributes === 'function') {
      customAttrs = options.attributes(href);
    } else if (
      typeof options.attributes === 'object' &&
      options.attributes !== null
    ) {
      customAttrs = options.attributes;
    }

    if (customAttrs) {
      for (const [k, v] of Object.entries(customAttrs)) {
        if (!['href', 'target', 'rel'].includes(k.toLowerCase())) {
          attrMap.set(k, v);
        }
      }
    }

    let result = `<a href="${escapeAttribute(href)}"`;
    if (target !== undefined) {
      result += ` target="${escapeAttribute(target)}"`;
    }
    if (rel !== undefined) {
      result += ` rel="${escapeAttribute(rel)}"`;
    }
    for (const [k, v] of attrMap.entries()) {
      if (v === '' && !rawAttrs.includes(`${k}=`)) {
        result += ` ${k}`;
      } else {
        result += ` ${k}="${escapeAttribute(v)}"`;
      }
    }
    result += '>';
    return result;
  });
}
